    public static void MakeToolWindow(IntPtr hwnd, bool noActivate)
    {
        var style = GetWindowLongPtr(hwnd, GWL_EXSTYLE).ToInt64();
        style |= WS_EX_TOOLWINDOW | WS_EX_TOPMOST;
        if (noActivate) style |= WS_EX_NOACTIVATE;
        SetWindowLongPtr(hwnd, GWL_EXSTYLE, new IntPtr(style));
    }

    public static RECT WorkAreaAt(POINT pt)
    {
        var info = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
        GetMonitorInfo(MonitorFromPoint(pt, MONITOR_DEFAULTTONEAREST), ref info);
        return info.rcWork;
    }

    /// <summary>Generates a zero-distance mouse move so an in-progress OLE drag re-evaluates the window under the cursor.</summary>
    public static void NudgeMouse()
    {
        var input = new INPUT { type = INPUT_MOUSE, mi = new MOUSEINPUT { dwFlags = MOUSEEVENTF_MOVE } };
        SendInput(1, [input], Marshal.SizeOf<INPUT>());
    }
